-- 1(e) Low-stock view
CREATE OR REPLACE VIEW v_low_stock AS
SELECT medicine_id,medicine_name,unit_price,stock_qty
FROM medicines WHERE stock_qty < 10;
SELECT * FROM v_low_stock ORDER BY medicine_id;

-- 1(f) Date-range index and matching plan query
CREATE INDEX IF NOT EXISTS ix_sales_medicine_sold_on
ON sales(medicine_id,sold_on);
EXPLAIN SELECT * FROM sales
WHERE medicine_id=1 AND sold_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

-- 1(g) Replace the selected day's summary; reruns never double-count.
CREATE OR REPLACE PROCEDURE pr_refresh_sales(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_day IS NULL THEN RAISE EXCEPTION 'Summary date cannot be NULL'; END IF;
    INSERT INTO daily_sales(sales_date,total_qty,total_amount)
    SELECT p_day,COALESCE(SUM(quantity),0),COALESCE(SUM(quantity*unit_price),0)
    FROM sales WHERE sold_on=p_day
    ON CONFLICT(sales_date) DO UPDATE SET
      total_qty=EXCLUDED.total_qty,total_amount=EXCLUDED.total_amount;
END; $$;
CALL pr_refresh_sales(CURRENT_DATE-1);
SELECT * FROM daily_sales ORDER BY sales_date;

